let confusables: Map<string, string> | null = null;
/** The UTS #39 confusables (confusables.ts, Unicode 16.0.0): each character a Trade Tag may hold, to its prototype. */
function confusableMap(): Map<string, string> {
  if (confusables === null) {
    confusables = new Map();
    for (const line of CONFUSABLES_DATA.split('\n')) {
      const tab = line.indexOf('\t');
      confusables.set(line.slice(0, tab), line.slice(tab + 1));
    }
  }
  return confusables;
}

/** Every character to its UTS #39 prototype (the skeleton's mapping step). */
function toPrototypes(s: string): string {
  const map = confusableMap();
  let out = '';
  for (const c of s) out += map.get(c) ?? c;
  return out;
}

/**
 * The look-alike fold: NFKD without its combining marks and invisible characters (accents off,
 * full-width forms plain), the reviewed Latin, Cyrillic and Greek folds, then the UTS #39
 * confusables skeleton's mapping (security review of
 * wip/lead-notes-all, M1: Lisu, Cherokee, Armenian and every other script's look-alikes, before and
 * after lower case, as a capital and its small letter may each have a prototype), lower case, the
 * reviewed Latin look-alikes (LOOK_ALIKE_LETTERS) and the Cyrillic and Greek ones (HOMOGLYPHS), then
 * 0→o, 1→l, i→l and rn→m. The skeleton maps m→rn, and the last step maps rn back to m, so both
 * sides of a comparison (a name and a reserved word or staff name, always through this function)
 * fold alike.
 */
export function lookAlikeKey(name: string): string {
  const strip = (x: string) => x.normalize('NFKD').replace(/[\p{M}\p{Default_Ignorable_Code_Point}]/gu, '');
  const fold = (x: string) => x.replace(FOLD_RE, (c) => FOLD[c]!);
  // The reviewed folds run first (the skeleton draws a small capital K as ĸ, not k); then the
  // skeleton on the capitals (a stored key is lower case, and a small Cherokee letter's prototype
  // is not its capital's: ꮇ → ʍ but Ꮇ → M), then again on the small letters, folding each time.
  const once = strip(toPrototypes(fold(strip(name).toLowerCase()).toUpperCase())).toLowerCase();
  const plain = fold(strip(toPrototypes(fold(once))).toLowerCase());
  return plain.replace(/[01i]/g, (c) => (c === '0' ? 'o' : 'l')).replace(/rn/g, 'm');
}

/**
 * The key a Trade Tag is compared with staff and owner Trade Tags by (F4; review of
 * third-signup-r3, M2): the look-alike fold with every non-letter and non-digit removed, as the
 * reserved-word check does, so `Mira,K`, `Mira K` and `Mira_K` all match the staff name `Mira.K`.
 */
export function staffNameKey(name: string): string {
  return lookAlikeKey(name).replace(/[^\p{L}\p{N}]+/gu, '');
}

const RESERVED_TOKENS = new Set(
  ['admin', 'administrator', 'moderator', 'mod', 'support', 'staff', 'owner', 'system', 'root', 'help', 'x2f', 'official'].map(lookAlikeKey),
);
/**
 * Whole names kept for the app's own example screens (lead, 12 Nov 2026: the first-trade tour's
 * pretend traders), so no real account can be shown as the model counterparty. Compared with
 * look-alikes folded and every non-letter and non-digit dropped (as `isReserved` flattens).
 */
const RESERVED_NAMES = new Set(['example_seller', 'example_buyer'].map((n) => lookAlikeKey(n).replace(/[^\p{L}\p{N}]+/gu, '')));
const F = { admin: lookAlikeKey('admin'), x2f: lookAlikeKey('x2f'), staff: lookAlikeKey('staff'), moderator: lookAlikeKey('moderator'), support: lookAlikeKey('support') };

/** Reserved words and their look-alikes, as whole tokens or by the prefix and suffix rules. */
function isReserved(key: string): boolean {
  const folded = lookAlikeKey(key);
  if (folded.split(/[^\p{L}\p{N}]+/u).some((t) => RESERVED_TOKENS.has(t))) return true;
  const flat = folded.replace(/[^\p{L}\p{N}]+/gu, '');
  if (RESERVED_NAMES.has(flat)) return true;
  return (
    flat.startsWith(F.admin) ||
    flat.startsWith(F.x2f) ||
    flat.startsWith(F.staff) ||
    flat.includes(F.moderator) ||
    flat.endsWith(F.support)
  );
}

