/** Digits drawn like letters, beyond lookAlikeKey's 0→o and 1→l: for the new-name check only. */
const DIGIT_LETTERS: Readonly<Record<string, string>> = { '3': 'e', '4': 'a', '5': 's', '7': 't', '8': 'b', '9': 'g' };

const ALNUM_OR_MARK = /[\p{L}\p{M}\p{Nd}]/u;

/**
 * A word break between the code points x and y (z follows y): a symbol or space, a change between
 * digit and letter, a lower-case letter then a capital (`SupportX`), or a capital before a capital
 * and a small letter (`XAdmin`). A combining mark joins its letter.
 */
function breakBetween(x: string, y: string, z: string | undefined): boolean {
  if (!ALNUM_OR_MARK.test(x) || !ALNUM_OR_MARK.test(y)) return true;
  if (/\p{M}/u.test(y)) return false;
  const dx = /\p{Nd}/u.test(x);
  if (dx !== /\p{Nd}/u.test(y)) return true;
  if (/\p{Ll}/u.test(x) && /\p{Lu}/u.test(y)) return true;
  return /\p{Lu}/u.test(x) && /\p{Lu}/u.test(y) && z !== undefined && /\p{Ll}/u.test(z);
}

/**
 * A name's look-alike skeleton for the new-name check, letter by letter: each character through
 * `lookAlikeKey` (accents, other scripts' look-alikes, 0→o, 1→l, i→l), the digits in DIGIT_LETTERS
 * as their letters, symbols dropped, rn as m. `cut[k]` says whether a word break (`breakBetween`)
 * falls before `s[k]` in the name as typed (true at both ends); `fromDigit[k]`, whether `s[k]` was
 * a digit.
 */
function newNameSkeleton(name: string): { s: string; cut: boolean[]; fromDigit: boolean[] } {
  const cps = [...name];
  const out: { c: string; from: number; to: number }[] = [];
  cps.forEach((c, i) => {
    for (const f of lookAlikeKey(c)) {
      const g = DIGIT_LETTERS[f] ?? f;
      if (/[\p{L}\p{N}]/u.test(g)) out.push({ c: g, from: i, to: i });
    }
  });
  for (let k = 0; k + 1 < out.length; k++) {
    if (out[k]!.c === 'r' && out[k + 1]!.c === 'n') out.splice(k, 2, { c: 'm', from: out[k]!.from, to: out[k + 1]!.to });
  }
  const cut = out.map((o, k) => {
    if (k === 0) return true;
    const prev = out[k - 1]!;
    if (prev.to === o.from) return false;
    for (let j = prev.to; j < o.from; j++) if (breakBetween(cps[j]!, cps[j + 1]!, cps[j + 2])) return true;
    return false;
  });
  cut.push(true);
  return { s: out.map((o) => o.c).join(''), cut, fromDigit: out.map((o) => /\p{Nd}/u.test(cps[o.from]!)) };
}

const NEW_RESERVED = NEW_RESERVED_WORDS.map((w) => newNameSkeleton(w).s);
const ORDINARY = ORDINARY_WORDS.map((w) => newNameSkeleton(w).s);
const letterCount = (s: string): number => (s.match(/\p{L}/gu) ?? []).length;

function occurrences(s: string, w: string): number[] {
  const at: number[] = [];
  for (let i = s.indexOf(w); i !== -1; i = s.indexOf(w, i + 1)) at.push(i);
  return at;
}

/**
 * The reserved-word rule for a **new or changed** Trade Tag (security follow-up, 23 Nov 2026;
 * login names are private and hold reserved words freely). On the name's look-alike skeleton (`newNameSkeleton`, digits that look like letters
 * folded too: `5upport1` reads `supportl`), a reserved word (NEW_RESERVED_WORDS) refuses the name
 * when it
 * 1. stands as a word of its own anywhere: a word break, or the name's start or end, on both sides
 *    (`Support1`, `SUPPORT1`, `SupportX`, `XAdmin12`, `Mod12345`, `Big_Owner`);
 * 2. starts or ends the name, its letters once the digits at the ends are set aside, or one of
 *    its words, even glued to other letters (`Rootuser`, `Theadmin`, `Helpdesk`, `Owner123`,
 *    `MyR00tacc`); or
 * 3. makes up at least half the name's letters (`SUPPORTX` aside, `Xadminxy`).
 * A reserved word spelt more in look-alike digits than letters counts only by rule 1, so
 * `Gamer007` (gamer, r007: one letter of four) passes while `Theadm1n` and `Myr00tacc` do not.
 * An occurrence glued inside an ordinary word (ORDINARY_WORDS, written as one word) does not count,
 * so `Modesty12`, `Teamwork9` and `Rootbeer7` pass while `ModEst12` and `Team_work` do not.
 */
function isReservedNewName(name: string): boolean {
  const { s, cut, fromDigit } = newNameSkeleton(name);
  const n = s.length;
  const firstLetter = fromDigit.indexOf(false);
  const lastLetter = fromDigit.lastIndexOf(false);
  const starts = new Set([0, firstLetter === -1 ? 0 : firstLetter]);
  const ends = new Set([n, lastLetter + 1]);
  const letters = letterCount(s);
  const unbroken = (c: number, d: number) => cut.slice(c + 1, d).every((x) => !x);
  for (const w of NEW_RESERVED) {
    for (const a of occurrences(s, w)) {
      const b = a + w.length;
      const covered = ORDINARY.some((e) => occurrences(s, e).some((c) => c <= a && b <= c + e.length && unbroken(c, c + e.length)));
      if (covered) continue;
      if (cut[a] && cut[b]) return true;
      // A reserved word spelt mostly in look-alike digits counts only as a word of its own
      // (`R00tR00t`): glued to letters it is a digit pad borrowing a letter (`Gamer007` holds
      // r007, one letter of four). One spelt mostly in letters (`Theadm1n`, `Myr00tacc`,
      // `0wnerxyz`) takes every rule.
      const digits = fromDigit.slice(a, b).filter(Boolean).length;
      if (2 * digits > b - a) continue;
      if (starts.has(a) || ends.has(b) || cut[a] || cut[b]) return true;
      if (2 * letterCount(w) >= letters) return true;
    }
  }
  return false;
}

/** The length rule, in code points (an astral character counts once); huge input is refused first. */
function lengthOk(input: string, min = NAME_MIN): boolean {
  if (input.length > MAX_RAW_LENGTH) return false;
  const len = [...input].length;
  return len >= min && len <= NAME_MAX;
}

function checkShape(input: string, min: number): NameCheck {
  if (typeof input !== 'string') return { ok: false, reason: 'characters' };
  if (!lengthOk(input, min)) return { ok: false, reason: 'length' };
  if (!NAME_RE.test(input)) return { ok: false, reason: 'characters' };
  return { ok: true, name: input, key: input.toLowerCase() };
}

