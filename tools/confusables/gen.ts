// Generates packages/accounts/src/confusables.ts from the Unicode confusables table (UTS #39), for
// the display-name look-alike fold (security review of wip/lead-notes-all, M1). Run:
//   curl -o /tmp/confusables.txt https://www.unicode.org/Public/security/16.0.0/confusables.txt
//   npx tsx tools/confusables/gen.ts /tmp/confusables.txt
// The input must match the pinned SHA-256 below; moving to a new Unicode version means re-pinning.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

export const VERSION = '16.0.0';
export const SHA256 = '95bd0aad6dced5ebc63436f459c06ab21a8d107cd842fb57f5c3a1e91bca8611';
const OUT = fileURLToPath(new URL('../../packages/accounts/src/confusables.ts', import.meta.url));

/** The characters a display name may hold at all (username.ts DISPLAY_CHARS), the space aside. */
const REACHABLE = /^[\p{L}\p{M}\p{Nd}$&!?.,'\-_@#%*+():]$/u;

export function build(text: string): string {
  const pairs: [string, string][] = [];
  for (const line of text.split('\n')) {
    const m = /^([0-9A-F ]+);\t([0-9A-F ]+);\tMA/.exec(line);
    if (!m) continue;
    const src = String.fromCodePoint(...m[1]!.trim().split(' ').map((h) => parseInt(h, 16)));
    if ([...src].length !== 1 || !REACHABLE.test(src) || src.normalize('NFKD') !== src) continue;
    // The prototype as the fold sees it: NFKD, no combining marks (case kept; the fold lowers it).
    const to = String.fromCodePoint(...m[2]!.trim().split(' ').map((h) => parseInt(h, 16)))
      .normalize('NFKD')
      .replace(/\p{M}/gu, '');
    if (to === src) continue;
    pairs.push([src, to]);
  }
  pairs.sort((a, b) => a[0].codePointAt(0)! - b[0].codePointAt(0)!);
  const body = pairs.map(([s, t]) => `${s}\t${t}`).join('\n');
  return `// GENERATED by tools/confusables/gen.ts from the Unicode confusables table, version ${VERSION}
// (https://www.unicode.org/Public/security/${VERSION}/confusables.txt, SHA-256 ${SHA256}).
// Do not edit. Only characters a display name may hold, NFKD-stable, mapped to their prototype
// (NFKD, combining marks removed). © Unicode, Inc.; terms of use: https://www.unicode.org/terms_of_use.html
/* eslint-disable */
export const CONFUSABLES_VERSION = '${VERSION}';
/** One "<character>\\t<prototype>" per line. */
export const CONFUSABLES_DATA = ${JSON.stringify(body)};
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const raw = readFileSync(process.argv[2]!);
  const sha = createHash('sha256').update(raw).digest('hex');
  if (sha !== SHA256) throw new Error(`confusables.txt SHA-256 ${sha}, expected ${SHA256} (version ${VERSION})`);
  writeFileSync(OUT, build(raw.toString('utf8')));
  console.log(`wrote ${OUT}`);
}
