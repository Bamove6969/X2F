// `npm run tokens`: writes apps/web/src/theme/tokens.css from design/design-system/tokens.json.
// apps/web/test/tokens.test.ts fails when the committed file is stale.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

export const TOKENS_JSON = fileURLToPath(new URL('../design/design-system/tokens.json', import.meta.url));
export const TOKENS_CSS = fileURLToPath(new URL('../apps/web/src/theme/tokens.css', import.meta.url));

interface ValueToken {
  name: string;
  value: string;
}

interface TypeStyle {
  name: string;
  fontSize: string;
  lineHeight: string;
  fontWeight: number;
  letterSpacing?: string;
}

export interface Tokens {
  color: {
    tokens: { name: string; value: { night: string; day: string } }[];
    /** Translucent overlays (the scrim behind sheets): the only rgba() values (design kit handoff 1.1). */
    scrims?: { name: string; value: { night: string; day: string } }[];
  };
  type: { families: Record<string, string>; groups: { name: string; family: string; styles: TypeStyle[] }[] };
  spacing: { tokens: ValueToken[] };
  radius: { tokens: ValueToken[] };
}

const NAME = /^[a-z][a-z0-9-]*$/;
// Values go into CSS verbatim, so only the shapes tokens.json uses are accepted.
const COLOUR = /^#[0-9a-f]{6}$/;
const BYTE = String.raw`(?:25[0-5]|2[0-4]\d|1\d\d|[1-9]?\d)`;
const ALPHA = String.raw`(?:0|1|0?\.\d{1,3})`;
const SCRIM = new RegExp(`^rgba\\(${BYTE},${BYTE},${BYTE},${ALPHA}\\)$`);
const LENGTH = /^-?\d+(\.\d+)?(px|em)$/;
const FAMILY = /^[A-Za-z0-9 ",-]+$/;

function check(ok: boolean, what: string): void {
  if (!ok) throw new Error(`tokens.json: unexpected ${what}`);
}

const decl = (name: string, value: string | number) => `  --x2f-${name}: ${value};`;

export function tokensToCss(t: Tokens): string {
  const night: string[] = [];
  const day: string[] = [];
  for (const c of t.color.tokens) {
    check(NAME.test(c.name), `colour name ${c.name}`);
    check(COLOUR.test(c.value.night) && COLOUR.test(c.value.day), `colour value for ${c.name}`);
    night.push(decl(c.name, c.value.night));
    day.push(decl(c.name, c.value.day));
  }
  for (const c of t.color.scrims ?? []) {
    check(NAME.test(c.name), `scrim name ${c.name}`);
    check(SCRIM.test(c.value.night) && SCRIM.test(c.value.day), `scrim value for ${c.name}`);
    night.push(decl(c.name, c.value.night));
    day.push(decl(c.name, c.value.day));
  }

  const shared: string[] = [];
  for (const s of [...t.spacing.tokens, ...t.radius.tokens]) {
    check(NAME.test(s.name) && LENGTH.test(s.value), `length token ${s.name}`);
    shared.push(decl(s.name, s.value));
  }
  for (const [name, family] of Object.entries(t.type.families)) {
    check(NAME.test(name) && FAMILY.test(family), `font family ${name}`);
    shared.push(decl(`font-${name}`, family));
  }
  for (const g of t.type.groups) {
    check(g.family in t.type.families, `family ${g.family} in group ${g.name}`);
    for (const s of g.styles) {
      check(NAME.test(s.name), `type style ${s.name}`);
      check(LENGTH.test(s.fontSize) && LENGTH.test(s.lineHeight) && Number.isInteger(s.fontWeight), `type values for ${s.name}`);
      shared.push(decl(`${s.name}-family`, `var(--x2f-font-${g.family})`));
      shared.push(decl(`${s.name}-size`, s.fontSize));
      shared.push(decl(`${s.name}-line`, s.lineHeight));
      shared.push(decl(`${s.name}-weight`, s.fontWeight));
      if (s.letterSpacing !== undefined) {
        check(LENGTH.test(s.letterSpacing), `letter spacing for ${s.name}`);
        shared.push(decl(`${s.name}-tracking`, s.letterSpacing));
      }
    }
  }

  return [
    '/* Generated by `npm run tokens` from design/design-system/tokens.json. Do not edit by hand. */',
    '',
    '/* Night is the default theme. */',
    ':root,',
    ':root[data-theme=night] {',
    '  color-scheme: dark;',
    ...night,
    '}',
    '',
    ':root[data-theme=day] {',
    '  color-scheme: light;',
    ...day,
    '}',
    '',
    ':root {',
    ...shared,
    '}',
    '',
  ].join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(TOKENS_CSS, tokensToCss(JSON.parse(readFileSync(TOKENS_JSON, 'utf8')) as Tokens));
  console.log('tokens: wrote apps/web/src/theme/tokens.css');
}
